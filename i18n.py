"""i18n.py — the Studio's translation catalogs (docs/TRANSLATING.md).

PURE: no panel imports. The panel calls `boot_payload()` from page() and
stamps the result into BOOT.i18n; `scripts/i18n.py` (export / import /
check) uses the same loaders so the tool and the runtime can never read the
files differently.

Files (all under i18n/studio/ at the repo root, never served as-is):

  en.json        the English SOURCE catalog. Generated by
                 `python3 scripts/i18n.py extract` from the markup
                 (data-i18n attributes in webapp/index.html) and the JS
                 (t()/tp() calls in webapp/js/*.js). English lives in the
                 code; this file is the list a translator works from, with a
                 context note and a length hint per string. Never hand-edit
                 the "text" fields — change the code and re-extract.
  <lang>.json    one per language, e.g. es.json, ja.json, zh-Hans.json:
                 {"meta": {"lang", "name", "dir"},
                  "strings": {key: text | {plural forms}},
                  "source": {key: hash of the English it was made from}}

Language pick (resolve()): the Studio setting `ui_language` when it names
an installed language; "auto" (the default) follows the Mac's own language
list, then the browser's Accept-Language, then English. A key with no
translation falls back to the English in the code — the page can never show
a raw key.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import subprocess
import sys
import threading
from pathlib import Path

ROOT = Path(__file__).resolve().parent
STUDIO_DIR = ROOT / "i18n" / "studio"
SOURCE_LANG = "en"

# Product and model names stay in English in every language.
PROTECTED_TERMS = (
    "Phosphene", "Phosphene Pro", "Pro", "Free", "Studio", "Remote",
    "LTX", "LTX 2.3", "LTX 2.5", "MiniMax", "MiniMax H3", "H3", "Hailuo",
    "MiniMax-H3-Image", "FLUX", "Qwen", "Gemma", "Ideogram", "YuE",
    "CivitAI", "Hugging Face", "LoRA", "Pinokio", "Q4", "Q8", "MLX",
    "Apple Silicon", "macOS", "Mac", "iPhone", "GitHub", "Discord",
)

# {name} placeholders and <0>…</0> / <1/> tag markers.
PLACEHOLDER_RE = re.compile(r"\{[A-Za-z_][A-Za-z0-9_]*\}")
MARKER_RE = re.compile(r"</?\d+/?>")

# CLDR plural categories a translator must supply, per language (base tag).
# Anything not listed gets one/other. The browser picks the category with
# Intl.PluralRules and falls back to "other" when a form is missing.
PLURAL_FORMS = {
    "ja": ["other"], "zh": ["other"], "ko": ["other"], "th": ["other"],
    "vi": ["other"], "id": ["other"], "ms": ["other"], "tr": ["one", "other"],
    "ru": ["one", "few", "many", "other"], "uk": ["one", "few", "many", "other"],
    "pl": ["one", "few", "many", "other"], "cs": ["one", "few", "many", "other"],
    "ar": ["zero", "one", "two", "few", "many", "other"],
    "he": ["one", "two", "other"], "fr": ["one", "many", "other"],
    "es": ["one", "many", "other"], "it": ["one", "many", "other"],
    "pt": ["one", "many", "other"],
}
RTL_LANGS = {"ar", "he", "fa", "ur", "yi"}

# Files in i18n/studio/ that are not languages.
NOT_LOCALES = {SOURCE_LANG, "areas", "notes"}

# One neutral file per language, no regional variants (owner, 13 Nov 2026):
# "es", "pt", "fr"… read fine everywhere; the only split is Chinese, where
# Simplified and Traditional are different scripts (zh-Hans first).
# Native names for the language menu (a locale file's meta.name wins).
NATIVE_NAMES = {
    "en": "English", "es": "Español", "de": "Deutsch", "fr": "Français",
    "it": "Italiano", "pt": "Português",
    "ja": "日本語", "zh-Hans": "简体中文", "zh-Hant": "繁體中文", "ko": "한국어",
    "ru": "Русский", "uk": "Українська", "pl": "Polski", "tr": "Türkçe",
    "ar": "العربية", "he": "עברית", "nl": "Nederlands", "sv": "Svenska",
}


def plural_forms(lang: str) -> list[str]:
    return PLURAL_FORMS.get(base_tag(lang), ["one", "other"])


def base_tag(lang: str) -> str:
    return (lang or "").replace("_", "-").split("-")[0].lower()


def text_hash(text) -> str:
    """Stable hash of an English text (a string or a plural dict)."""
    canon = json.dumps(text, ensure_ascii=False, sort_keys=True)
    return hashlib.sha1(canon.encode("utf-8")).hexdigest()[:10]


def placeholders(text) -> set[str]:
    """Every {name} and tag marker in a text (string or plural dict)."""
    if isinstance(text, dict):
        out: set[str] = set()
        for v in text.values():
            out |= placeholders(v)
        return out
    s = str(text or "")
    return set(PLACEHOLDER_RE.findall(s)) | set(MARKER_RE.findall(s))


def _read_json(path: Path) -> dict:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


_CACHE: dict = {}
_CACHE_LOCK = threading.Lock()


def _cached(path: Path) -> dict:
    """Read a catalog once per mtime (the page is rendered per request)."""
    try:
        mt = path.stat().st_mtime_ns
    except OSError:
        return {}
    with _CACHE_LOCK:
        hit = _CACHE.get(path)
        if hit and hit[0] == mt:
            return hit[1]
    data = _read_json(path)
    with _CACHE_LOCK:
        _CACHE[path] = (mt, data)
    return data


def source_catalog(base: Path = STUDIO_DIR) -> dict:
    """{key: {"text", "note", "max"?, "where"}} — the English source."""
    return _cached(base / f"{SOURCE_LANG}.json").get("strings", {}) or {}


def locale_file(lang: str, base: Path = STUDIO_DIR) -> Path:
    return base / f"{lang}.json"


def load_locale(lang: str, base: Path = STUDIO_DIR) -> dict:
    data = _cached(locale_file(lang, base))
    return {
        "meta": data.get("meta", {}) or {},
        "strings": data.get("strings", {}) or {},
        "source": data.get("source", {}) or {},
        "reviewed": data.get("reviewed", {}) or {},
    }


def available(base: Path = STUDIO_DIR) -> list[dict]:
    """[{code, name, dir}] — English first, then every installed locale.
    Pseudo-locales (en-XA, ar-XB) are listed only when present on disk —
    they are generated for layout checks and are not committed."""
    out = [{"code": "en", "name": "English", "dir": "ltr"}]
    try:
        files = sorted(base.glob("*.json"))
    except OSError:
        files = []
    for p in files:
        code = p.stem
        if code in NOT_LOCALES:
            continue
        meta = load_locale(code, base)["meta"]
        out.append({
            "code": code,
            "name": meta.get("name") or NATIVE_NAMES.get(code, code),
            "dir": meta.get("dir") or ("rtl" if base_tag(code) in RTL_LANGS else "ltr"),
        })
    return out


# ---------------------------------------------------------------- language pick

_MAC_LANGS: list[str] | None = None


def mac_languages() -> list[str]:
    """The Mac's preferred-language list (System Settings > Language &
    Region), e.g. ["ja-JP", "en-US"]. Read once per process; [] off macOS."""
    global _MAC_LANGS
    if _MAC_LANGS is not None:
        return _MAC_LANGS
    langs: list[str] = []
    if sys.platform == "darwin" and not os.environ.get("PHOSPHENE_I18N_NO_SYSTEM"):
        try:
            raw = subprocess.run(
                ["defaults", "read", "-g", "AppleLanguages"],
                capture_output=True, text=True, timeout=3).stdout
            langs = re.findall(r'"?([A-Za-z]{2,3}(?:-[A-Za-z0-9]+)*)"?\s*[,)]', raw)
        except Exception:                                    # noqa: BLE001
            langs = []
    _MAC_LANGS = langs
    return langs


def _accept_language(header: str) -> list[str]:
    items = []
    for i, part in enumerate((header or "").split(",")):
        bits = part.strip().split(";")
        tag = bits[0].strip()
        if not tag or tag == "*":
            continue
        q = 1.0
        for b in bits[1:]:
            if b.strip().startswith("q="):
                try:
                    q = float(b.strip()[2:])
                except ValueError:
                    q = 0.0
        if q <= 0:
            continue                      # q=0 means "not acceptable"
        items.append((-q, i, tag))
    return [t for _, _, t in sorted(items)]


def match(tag: str, codes: list[str]) -> str | None:
    """Best installed code for one language tag: exact, then script/region
    aware (zh-Hant-TW → zh-Hant, zh-CN → zh-Hans), then the base language."""
    if not tag:
        return None
    t = tag.replace("_", "-")
    lower = {c.lower(): c for c in codes}
    if t.lower() in lower:
        return lower[t.lower()]
    parts = t.split("-")
    b = parts[0].lower()
    if b == "zh":
        rest = [p.lower() for p in parts[1:]]
        want = "zh-hant" if ({"hant", "tw", "hk", "mo"} & set(rest)) else "zh-hans"
        if want in lower:
            return lower[want]
    if len(parts) >= 2 and f"{b}-{parts[1]}".lower() in lower:
        return lower[f"{b}-{parts[1]}".lower()]
    if b in lower:
        return lower[b]
    if b == "zh":                                     # zh-Hant with only zh-Hans installed: English, never the other script
        return None
    for c in codes:                                   # pt-PT asked, pt-BR installed
        if c.lower().split("-")[0] == b:
            return c
    return None


def resolve(setting: str = "auto", accept_language: str = "",
            base: Path = STUDIO_DIR) -> str:
    codes = [a["code"] for a in available(base)]
    s = (setting or "auto").strip()
    if s and s != "auto":
        return match(s, codes) or SOURCE_LANG
    for tag in mac_languages() + _accept_language(accept_language):
        m = match(tag, codes)
        if m:
            return m
    return SOURCE_LANG


def live_strings(lang: str, base: Path = STUDIO_DIR) -> dict:
    """The translations the page may use: every key still in the English
    catalog whose translation keeps the English placeholders. A string the
    English has since changed keeps showing its old translation as long as
    its placeholders still match (better than dropping to English); the
    export marks it as changed so the next round refreshes it."""
    if lang == SOURCE_LANG:
        return {}
    src = source_catalog(base)
    out = {}
    for k, v in load_locale(lang, base)["strings"].items():
        ent = src.get(k)
        if not ent or v in ("", None):
            continue
        if placeholders(v) - placeholders(ent.get("text")):
            continue                      # a marker the English no longer has
        out[k] = v
    return out


def boot_payload(setting: str = "auto", accept_language: str = "",
                 base: Path = STUDIO_DIR) -> dict:
    """BOOT.i18n — {lang, dir, setting, available, strings}."""
    langs = available(base)
    lang = resolve(setting, accept_language, base)
    meta = next((a for a in langs if a["code"] == lang), langs[0])
    return {
        "lang": lang,
        "dir": meta["dir"],
        "setting": (setting or "auto"),
        "available": langs,
        "strings": live_strings(lang, base),
    }
